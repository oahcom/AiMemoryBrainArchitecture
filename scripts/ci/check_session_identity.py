#!/usr/bin/env python3
"""Session identity ratchet: detect unparseable or contradictory session claims.

Usage:
    python3 scripts/ci/check_session_identity.py
    python3 scripts/ci/check_session_identity.py --root /path/to/repository
    python3 scripts/ci/check_session_identity.py --write-baseline
    python3 scripts/ci/check_session_identity.py --baseline PATH

Baseline generation command:
    python3 scripts/ci/check_session_identity.py --write-baseline

The baseline freezes historical violations. After initial generation,
subsequent updates may only remove entries, never add them.
YAML parsing failures are never suppressible by the baseline.

This checker deliberately does not modify the existing Session Evidence
validator. It checks semantic session identity, not evidence-file shape,
hashes, byte counts, or evidence-reference consistency.

Dependencies: Python standard library and PyYAML.
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:
    print(
        "ERROR: PyYAML is required; install PyYAML==6.0.2",
        file=sys.stderr,
    )
    raise SystemExit(2)


DEFAULT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_BASELINE = Path("scripts/ci/baselines/session-identity.txt")

UUID_RE = re.compile(
    r"^[0-9a-fA-F]{8}-"
    r"[0-9a-fA-F]{4}-"
    r"[48][0-9a-fA-F]{3}-"
    r"[89abAB][0-9a-fA-F]{3}-"
    r"[0-9a-fA-F]{12}$"
)

CONV_RE = re.compile(
    r"^conv_[0-9a-fA-F]{32,}$",
    re.IGNORECASE,
)

SENTINELS = {
    "NOT_RECORDED",
    "NOT_AVAILABLE",
    "NOT_EXPOSED_BY_PLATFORM",
}

VALID_STATUSES = {
    "RECORDED",
    "NOT_RECORDED",
}

BASELINE_HEADER = (
    "# Generated by: python3 scripts/ci/check_session_identity.py "
    "--write-baseline\n"
    "# Ratchet rule: may only shrink; entries must never be added\n"
    "# Gate input: this file is consumed by "
    "scripts/ci/check_session_identity.py\n"
    "# (generated by --write-baseline; do not edit by hand)\n"
)


@dataclass(frozen=True)
class Violation:
    code: str
    path: str
    entry_index: str
    detail: str

    @property
    def identity(self) -> str:
        return f"{self.code} {self.path}#{self.entry_index}"

    def render(self) -> str:
        return f"{self.identity} {self.detail}"


def is_parseable_session(value: Any) -> bool:
    """Return whether value matches an accepted session-ID syntax.

    Accepted formats:

    1. UUID v4:
       8-4-4-4-12 hexadecimal characters, version nibble 4,
       RFC 4122 variant nibble 8, 9, A or B.

    2. UUID v8:
       8-4-4-4-12 hexadecimal characters, version nibble 8,
       RFC 4122 variant nibble 8, 9, A or B.

    3. Platform conversation identifier:
       conv_ followed by at least 32 hexadecimal characters.

    UUID versions other than 4 and 8 are rejected. UUIDs with a
    non-RFC-4122 variant are rejected.

    This validates syntax only. It does not prove that a session
    exists or that its evidence is authentic.
    """
    if not isinstance(value, str):
        return False

    value = value.strip()

    if UUID_RE.fullmatch(value):
        return True

    return bool(CONV_RE.fullmatch(value))


def _normalise_scalar(value: Any) -> str:
    if isinstance(value, str):
        return value.strip()
    return ""


def _read_yaml(path: Path) -> Any:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def _discover_manifests(root: Path) -> list[Path]:
    work_items = root / "14-ai-development" / "work-items"

    if not work_items.is_dir():
        return []

    return sorted(work_items.glob("*/manifest.yaml"))


def _entry_violations(
    manifest_path: str,
    entry_index: int,
    entry: Any,
) -> list[Violation]:
    result: list[Violation] = []
    index = str(entry_index)

    if not isinstance(entry, dict):
        return [
            Violation(
                "SESSION_FIELD_MISSING",
                manifest_path,
                index,
                "session_evidence entry must be a mapping",
            )
        ]

    required_fields = (
        "implementing_ai_session",
        "session_reference_status",
    )

    missing = [
        field
        for field in required_fields
        if field not in entry or entry[field] is None
    ]

    for field in missing:
        result.append(
            Violation(
                "SESSION_FIELD_MISSING",
                manifest_path,
                index,
                f"required field {field!r} is missing",
            )
        )

    if missing:
        return result

    raw_status = _normalise_scalar(
        entry["session_reference_status"]
    ).upper()

    raw_session = entry["implementing_ai_session"]

    if raw_status not in VALID_STATUSES:
        result.append(
            Violation(
                "SESSION_STATUS_INVALID",
                manifest_path,
                index,
                f"unsupported session_reference_status {raw_status!r}",
            )
        )
        return result

    if not isinstance(raw_session, str) or not raw_session.strip():
        result.append(
            Violation(
                "SESSION_FIELD_MISSING",
                manifest_path,
                index,
                "implementing_ai_session must be a non-empty string",
            )
        )
        return result

    session_value = raw_session.strip()
    sentinel = session_value.upper() in SENTINELS
    parseable = is_parseable_session(session_value)

    if raw_status == "RECORDED":
        if sentinel:
            result.append(
                Violation(
                    "SESSION_RECORDED_SENTINEL",
                    manifest_path,
                    index,
                    f"RECORDED cannot use sentinel {session_value!r}",
                )
            )
        elif not parseable:
            result.append(
                Violation(
                    "SESSION_UNPARSEABLE",
                    manifest_path,
                    index,
                    f"RECORDED value {session_value!r} is not a supported session identifier",
                )
            )

    elif raw_status == "NOT_RECORDED":
        if not sentinel:
            result.append(
                Violation(
                    "SESSION_SENTINEL_MISMATCH",
                    manifest_path,
                    index,
                    f"NOT_RECORDED cannot contain a human label or identifier: {session_value!r}",
                )
            )

    return result


def scan_tree(root: Path) -> tuple[list[Violation], int]:
    """Return (violations, no_evidence_section_count)."""
    violations: list[Violation] = []
    no_evidence_section = 0

    for path in _discover_manifests(root):
        relative_path = path.relative_to(root).as_posix()

        try:
            document = _read_yaml(path)
        except (OSError, UnicodeError, yaml.YAMLError) as exc:
            violations.append(
                Violation(
                    "SESSION_YAML_INVALID",
                    relative_path,
                    "manifest",
                    f"cannot parse manifest YAML: {type(exc).__name__}: {exc}",
                )
            )
            continue

        if not isinstance(document, dict):
            violations.append(
                Violation(
                    "SESSION_YAML_INVALID",
                    relative_path,
                    "manifest",
                    "manifest top-level YAML must be a mapping",
                )
            )
            continue

        if "session_evidence" not in document:
            no_evidence_section += 1
            continue

        entries = document["session_evidence"]

        if not isinstance(entries, list):
            violations.append(
                Violation(
                    "SESSION_FIELD_MISSING",
                    relative_path,
                    "manifest",
                    "session_evidence must be a list",
                )
            )
            continue

        for index, entry in enumerate(entries, start=1):
            violations.extend(
                _entry_violations(
                    relative_path,
                    index,
                    entry,
                )
            )

    return violations, no_evidence_section


def _parse_baseline(path: Path) -> set[str]:
    if not path.is_file():
        raise FileNotFoundError(str(path))

    entries: set[str] = set()

    for line_number, raw in enumerate(
        path.read_text(encoding="utf-8").splitlines(),
        start=1,
    ):
        line = raw.strip()

        if not line or line.startswith("#"):
            continue

        parts = line.split(" ", 1)

        if len(parts) != 2:
            raise ValueError(
                f"invalid baseline entry at line {line_number}: {line!r}"
            )

        code, location = parts

        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", code):
            raise ValueError(
                f"invalid violation code at line {line_number}"
            )

        if "#" not in location:
            raise ValueError(
                f"invalid violation location at line {line_number}"
            )

        identity = f"{code} {location}"

        if identity in entries:
            raise ValueError(
                f"duplicate baseline entry at line {line_number}: {identity}"
            )

        entries.add(identity)

    return entries


def _baseline_is_bootstrap(path: Path) -> bool:
    if not path.exists():
        return False

    lines = path.read_text(encoding="utf-8").splitlines()

    return not any(
        line.strip() and not line.lstrip().startswith("#")
        for line in lines
    )


def _write_baseline(
    path: Path,
    violations: list[Violation],
) -> int:
    """Generate initial baseline or shrink existing baseline only."""
    identities = {
        violation.identity
        for violation in violations
        if violation.code != "SESSION_YAML_INVALID"
    }

    if path.exists() and not _baseline_is_bootstrap(path):
        try:
            previous = _parse_baseline(path)
        except (OSError, UnicodeError, ValueError) as exc:
            print(
                f"ERROR: cannot update invalid baseline: {exc}",
                file=sys.stderr,
            )
            return 2

        additions = identities - previous

        if additions:
            print(
                "ERROR: baseline expansion refused; new violations "
                "must be fixed, not grandfathered:",
                file=sys.stderr,
            )
            for item in sorted(additions):
                print(f"  {item}", file=sys.stderr)
            return 1

    path.parent.mkdir(parents=True, exist_ok=True)

    body = BASELINE_HEADER
    if identities:
        body += "\n".join(sorted(identities)) + "\n"

    path.write_text(body, encoding="utf-8", newline="\n")

    print(
        f"SESSION IDENTITY BASELINE: wrote {len(identities)} entries "
        f"to {path.as_posix()}"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Check session identity using a shrink-only baseline."
    )
    parser.add_argument(
        "--baseline",
        type=Path,
        default=DEFAULT_BASELINE,
        help="baseline path relative to --root (default: %(default)s)",
    )
    parser.add_argument(
        "--write-baseline",
        action="store_true",
        help="generate or shrink the baseline; expansion is refused",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=DEFAULT_ROOT,
        help="repository root (default: script-derived repository root)",
    )

    args = parser.parse_args(argv)

    root = args.root.resolve()
    baseline_path = (
        args.baseline
        if args.baseline.is_absolute()
        else root / args.baseline
    )

    if not root.is_dir():
        print(
            f"ERROR: repository root does not exist: {root}",
            file=sys.stderr,
        )
        return 2

    try:
        violations, no_evidence_section = scan_tree(root)
    except Exception as exc:
        print(
            f"ERROR: unable to scan repository: "
            f"{type(exc).__name__}: {exc}",
            file=sys.stderr,
        )
        return 2

    if args.write_baseline:
        return _write_baseline(baseline_path, violations)

    try:
        baseline = _parse_baseline(baseline_path)
    except FileNotFoundError:
        print(
            f"ERROR: baseline missing: {baseline_path}",
            file=sys.stderr,
        )
        return 2
    except (OSError, UnicodeError, ValueError) as exc:
        print(
            f"ERROR: invalid baseline: {exc}",
            file=sys.stderr,
        )
        return 2

    current = {
        violation.identity
        for violation in violations
    }

    new = {
        violation.identity
        for violation in violations
        if (
            violation.code == "SESSION_YAML_INVALID"
            or violation.identity not in baseline
        )
    }

    baselined = current - new

    for violation in violations:
        print(violation.render())

    stale = baseline - current

    for identity in sorted(stale):
        print(
            f"BASELINE_STALE {identity} "
            "finding no longer exists; regenerate the baseline"
        )

    print(
        f"SESSION IDENTITY: {len(violations)} violations, "
        f"{len(baselined)} baselined, {len(new)} new"
    )
    print(
        f"SESSION IDENTITY INVENTORY: "
        f"no_evidence_section={no_evidence_section}"
    )

    if new or stale:
        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
