#!/usr/bin/env python3
"""Session identity ratchet with explicit, Git-verified baseline bootstrap.

Normal checks require a committed baseline. --write-baseline may only shrink
that baseline. Initial creation requires --bootstrap-baseline --base-ref REF.

Bootstrap rules:
* REF must resolve to a commit in a non-shallow Git repository.
* REF must have a merge base with HEAD.
* REF's tree must not contain the baseline file.
* The baseline is generated from REF's work-items tree, never from HEAD.
* Every current violation must already exist in REF; current YAML errors
  always reject bootstrap.
* If a baseline already exists in the working tree, it must exactly match
  the baseline derived from REF. This makes a repeated bootstrap idempotent.

Deleting a baseline never enables ordinary checking or --write-baseline:
both fail with exit code 2. Once the baseline is on the target branch,
bootstrap also refuses because REF contains that baseline.

Dependencies: Python standard library and PyYAML.
"""
from __future__ import annotations

import argparse
import io
import re
import subprocess
import sys
import tarfile
import tempfile
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any

try:
    import yaml
except ImportError:
    print(
        "ERROR: PyYAML is required; install PyYAML==6.0.2",
        file=sys.stderr,
    )
    raise SystemExit(2)


DEFAULT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_BASELINE = Path("scripts/ci/baselines/session-identity.txt")
WORK_ITEMS = "14-ai-development/work-items"

UUID_RE = re.compile(
    r"^[0-9a-fA-F]{8}-"
    r"[0-9a-fA-F]{4}-"
    r"[48][0-9a-fA-F]{3}-"
    r"[89abAB][0-9a-fA-F]{3}-"
    r"[0-9a-fA-F]{12}$"
)
CONV_RE = re.compile(r"^conv_[0-9a-fA-F]{32,}$", re.IGNORECASE)

SENTINELS = {
    "NOT_RECORDED",
    "NOT_AVAILABLE",
    "NOT_EXPOSED_BY_PLATFORM",
}
VALID_STATUSES = {"RECORDED", "NOT_RECORDED"}

BASELINE_HEADER = (
    "# Generated by: python3 scripts/ci/check_session_identity.py "
    "--write-baseline\n"
    "# Ratchet rule: may only shrink; entries must never be added\n"
    "# Gate input: this file is consumed by "
    "scripts/ci/check_session_identity.py\n"
    "# (generated by --write-baseline; do not edit by hand)\n"
)


@dataclass(frozen=True)
class Violation:
    code: str
    path: str
    entry_index: str
    detail: str

    @property
    def identity(self) -> str:
        return f"{self.code} {self.path}#{self.entry_index}"

    def render(self) -> str:
        return f"{self.identity} {self.detail}"


def is_parseable_session(value: Any) -> bool:
    """Accept UUID v4/v8 with RFC variant, or platform conv_ identifiers."""
    if not isinstance(value, str):
        return False
    value = value.strip()
    return bool(UUID_RE.fullmatch(value) or CONV_RE.fullmatch(value))


def _normalise_scalar(value: Any) -> str:
    return value.strip() if isinstance(value, str) else ""


def _read_yaml(path: Path) -> Any:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def _discover_manifests(root: Path) -> list[Path]:
    work_items = root / WORK_ITEMS
    if not work_items.is_dir():
        return []
    return sorted(work_items.glob("*/manifest.yaml"))


def _entry_violations(
    manifest_path: str,
    entry_index: int,
    entry: Any,
) -> list[Violation]:
    result: list[Violation] = []
    index = str(entry_index)

    if not isinstance(entry, dict):
        return [
            Violation(
                "SESSION_FIELD_MISSING",
                manifest_path,
                index,
                "session_evidence entry must be a mapping",
            )
        ]

    required = ("implementing_ai_session", "session_reference_status")
    missing = [
        field for field in required
        if field not in entry or entry[field] is None
    ]
    for field in missing:
        result.append(
            Violation(
                "SESSION_FIELD_MISSING",
                manifest_path,
                index,
                f"required field {field!r} is missing",
            )
        )
    if missing:
        return result

    status = _normalise_scalar(
        entry["session_reference_status"]
    ).upper()
    raw_session = entry["implementing_ai_session"]

    if status not in VALID_STATUSES:
        return [
            Violation(
                "SESSION_STATUS_INVALID",
                manifest_path,
                index,
                f"unsupported session_reference_status {status!r}",
            )
        ]

    if not isinstance(raw_session, str) or not raw_session.strip():
        return [
            Violation(
                "SESSION_FIELD_MISSING",
                manifest_path,
                index,
                "implementing_ai_session must be a non-empty string",
            )
        ]

    session = raw_session.strip()
    sentinel = session.upper() in SENTINELS
    parseable = is_parseable_session(session)

    if status == "RECORDED":
        if sentinel:
            result.append(
                Violation(
                    "SESSION_RECORDED_SENTINEL",
                    manifest_path,
                    index,
                    f"RECORDED cannot use sentinel {session!r}",
                )
            )
        elif not parseable:
            result.append(
                Violation(
                    "SESSION_UNPARSEABLE",
                    manifest_path,
                    index,
                    f"RECORDED value {session!r} is not a supported session identifier",
                )
            )
    elif not sentinel:
        result.append(
            Violation(
                "SESSION_SENTINEL_MISMATCH",
                manifest_path,
                index,
                f"NOT_RECORDED cannot contain a human label or identifier: {session!r}",
            )
        )

    return result


def scan_tree(root: Path) -> tuple[list[Violation], int]:
    """Return (violations, manifests without session_evidence)."""
    violations: list[Violation] = []
    no_evidence_section = 0

    for path in _discover_manifests(root):
        relative = path.relative_to(root).as_posix()
        try:
            document = _read_yaml(path)
        except (OSError, UnicodeError, yaml.YAMLError) as exc:
            violations.append(
                Violation(
                    "SESSION_YAML_INVALID",
                    relative,
                    "manifest",
                    f"cannot parse manifest YAML: {type(exc).__name__}: {exc}",
                )
            )
            continue

        if not isinstance(document, dict):
            violations.append(
                Violation(
                    "SESSION_YAML_INVALID",
                    relative,
                    "manifest",
                    "manifest top-level YAML must be a mapping",
                )
            )
            continue

        if "session_evidence" not in document:
            no_evidence_section += 1
            continue

        entries = document["session_evidence"]
        if not isinstance(entries, list):
            violations.append(
                Violation(
                    "SESSION_FIELD_MISSING",
                    relative,
                    "manifest",
                    "session_evidence must be a list",
                )
            )
            continue

        for index, entry in enumerate(entries, start=1):
            violations.extend(_entry_violations(relative, index, entry))

    return violations, no_evidence_section


def _parse_baseline(path: Path) -> set[str]:
    if not path.is_file():
        raise FileNotFoundError(str(path))

    entries: set[str] = set()
    for line_number, raw in enumerate(
        path.read_text(encoding="utf-8").splitlines(),
        start=1,
    ):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue

        parts = line.split(" ", 1)
        if len(parts) != 2:
            raise ValueError(
                f"invalid baseline entry at line {line_number}: {line!r}"
            )

        code, location = parts
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", code):
            raise ValueError(
                f"invalid violation code at line {line_number}"
            )
        if "#" not in location:
            raise ValueError(
                f"invalid violation location at line {line_number}"
            )

        identity = f"{code} {location}"
        if identity in entries:
            raise ValueError(
                f"duplicate baseline entry at line {line_number}: {identity}"
            )
        entries.add(identity)

    return entries


def _identities(violations: list[Violation]) -> set[str]:
    return {
        violation.identity
        for violation in violations
        if violation.code != "SESSION_YAML_INVALID"
    }


def _write_baseline(path: Path, violations: list[Violation]) -> int:
    """Shrink an existing baseline; never create or expand it."""
    if not path.exists():
        print(
            f"ERROR: baseline missing: {path}; "
            "use --bootstrap-baseline --base-ref REF for initial creation",
            file=sys.stderr,
        )
        return 2

    try:
        previous = _parse_baseline(path)
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"ERROR: cannot update invalid baseline: {exc}", file=sys.stderr)
        return 2

    current = _identities(violations)
    additions = current - previous
    if additions:
        print(
            "ERROR: baseline expansion refused; new violations "
            "must be fixed, not grandfathered:",
            file=sys.stderr,
        )
        for identity in sorted(additions):
            print(f"  {identity}", file=sys.stderr)
        return 1

    _write_baseline_bytes(path, current)
    print(
        f"SESSION IDENTITY BASELINE: wrote {len(current)} entries "
        f"to {path.as_posix()}"
    )
    return 0


def _write_baseline_bytes(path: Path, identities: set[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = BASELINE_HEADER
    if identities:
        body += "\n".join(sorted(identities)) + "\n"
    path.write_text(body, encoding="utf-8", newline="\n")


def _git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(root), *args],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )


def _git_text(root: Path, *args: str) -> str:
    result = _git(root, *args)
    if result.returncode != 0:
        message = result.stderr.decode("utf-8", errors="replace").strip()
        raise RuntimeError(message or f"git {' '.join(args)} failed")
    return result.stdout.decode("utf-8", errors="strict").strip()


def _baseline_repo_path(root: Path, baseline_path: Path) -> str:
    try:
        relative = baseline_path.resolve().relative_to(root.resolve())
    except ValueError as exc:
        raise RuntimeError("baseline path must be inside --root") from exc
    return PurePosixPath(*relative.parts).as_posix()


def _extract_work_items_archive(root: Path, ref: str) -> Path:
    """Export only the work-items subtree from REF into a temporary tree."""
    archive = _git(root, "archive", "--format=tar", ref, WORK_ITEMS)
    if archive.returncode != 0:
        message = archive.stderr.decode("utf-8", errors="replace").strip()
        raise RuntimeError(message or "git archive failed")

    temporary = Path(tempfile.mkdtemp(prefix="session-identity-base-"))
    try:
        with tarfile.open(fileobj=io.BytesIO(archive.stdout), mode="r:") as tar:
            for member in tar.getmembers():
                member_path = PurePosixPath(member.name)
                if (
                    member_path.is_absolute()
                    or ".." in member_path.parts
                    or not (
                        member.isdir()
                        or member.isfile()
                    )
                ):
                    raise RuntimeError(
                        f"unsafe or unsupported git archive member: {member.name}"
                    )

                destination = temporary.joinpath(*member_path.parts)
                if member.isdir():
                    destination.mkdir(parents=True, exist_ok=True)
                    continue

                destination.parent.mkdir(parents=True, exist_ok=True)
                source = tar.extractfile(member)
                if source is None:
                    raise RuntimeError(
                        f"cannot read git archive member: {member.name}"
                    )
                destination.write_bytes(source.read())
    except Exception:
        import shutil
        shutil.rmtree(temporary, ignore_errors=True)
        raise

    return temporary


def _bootstrap_baseline(
    root: Path,
    baseline_path: Path,
    base_ref: str | None,
    current_violations: list[Violation],
) -> int:
    """Create the baseline from a verified target-branch Git tree."""
    if not base_ref:
        print(
            "ERROR: --bootstrap-baseline requires --base-ref REF",
            file=sys.stderr,
        )
        return 2

    try:
        shallow = _git_text(root, "rev-parse", "--is-shallow-repository")
        if shallow == "true":
            raise RuntimeError(
                "shallow repository; fetch complete history before bootstrap"
            )

        resolved_ref = _git_text(root, "rev-parse", "--verify", f"{base_ref}^{{commit}}")
        _git_text(root, "merge-base", "HEAD", resolved_ref)

        baseline_repo_path = _baseline_repo_path(root, baseline_path)
        exists_in_base = _git(
            root,
            "cat-file",
            "-e",
            f"{resolved_ref}:{baseline_repo_path}",
        )
        if exists_in_base.returncode == 0:
            raise RuntimeError(
                "bootstrap refused: target base tree already contains "
                f"{baseline_repo_path}; baseline deletion cannot reset the ratchet"
            )

        # Distinguish a genuinely absent path from an invalid/unreadable tree.
        _git_text(root, "cat-file", "-e", f"{resolved_ref}^{{tree}}")

        base_root = _extract_work_items_archive(root, resolved_ref)
        try:
            base_violations, _ = scan_tree(base_root)
        finally:
            import shutil
            shutil.rmtree(base_root, ignore_errors=True)

        if any(v.code == "SESSION_YAML_INVALID" for v in base_violations):
            raise RuntimeError(
                "bootstrap refused: target base tree contains invalid manifest YAML"
            )

        base_identities = _identities(base_violations)

        if any(v.code == "SESSION_YAML_INVALID" for v in current_violations):
            raise RuntimeError(
                "bootstrap refused: current tree contains SESSION_YAML_INVALID"
            )

        current_identities = _identities(current_violations)
        introduced = current_identities - base_identities
        if introduced:
            print(
                "ERROR: bootstrap refused; current tree contains violations "
                "not present in the target base tree:",
                file=sys.stderr,
            )
            for identity in sorted(introduced):
                print(f"  {identity}", file=sys.stderr)
            return 1

        # A previous successful bootstrap in this working tree is accepted
        # only when its bytes parse to exactly the same base-tree debt set.
        if baseline_path.exists():
            existing = _parse_baseline(baseline_path)
            if existing != base_identities:
                raise RuntimeError(
                    "bootstrap refused: existing working-tree baseline "
                    "does not exactly match the target base tree"
                )

        _write_baseline_bytes(baseline_path, base_identities)
        print(
            f"SESSION IDENTITY BASELINE: bootstrapped {len(base_identities)} "
            f"entries from {resolved_ref} into {baseline_path.as_posix()}"
        )
        return 0

    except (OSError, UnicodeError, ValueError, RuntimeError) as exc:
        print(f"ERROR: bootstrap cannot verify Git base: {exc}", file=sys.stderr)
        return 2


def _print_check_result(
    violations: list[Violation],
    no_evidence_section: int,
    baseline: set[str],
) -> int:
    current = {violation.identity for violation in violations}
    new = {
        violation.identity
        for violation in violations
        if (
            violation.code == "SESSION_YAML_INVALID"
            or violation.identity not in baseline
        )
    }
    baselined = current - new

    for violation in violations:
        print(violation.render())

    stale = baseline - current
    for identity in sorted(stale):
        print(
            f"BASELINE_STALE {identity} "
            "finding no longer exists; regenerate the baseline"
        )

    print(
        f"SESSION IDENTITY: {len(violations)} violations, "
        f"{len(baselined)} baselined, {len(new)} new"
    )
    print(
        f"SESSION IDENTITY INVENTORY: "
        f"no_evidence_section={no_evidence_section}"
    )
    return 1 if new or stale else 0



def _diff_base_check(root: Path, base_ref: str, current_violations: list[Violation]) -> int:
    """Compare current findings with a verified Git base; never access a snapshot baseline."""
    try:
        if _git_text(root, "rev-parse", "--is-inside-work-tree") != "true":
            raise RuntimeError("repository root is not inside a Git work tree")
        if _git_text(root, "rev-parse", "--is-shallow-repository") == "true":
            raise RuntimeError("shallow repository; fetch complete history first")
        resolved_ref = _git_text(root, "rev-parse", "--verify", f"{base_ref}^{{commit}}")
        _git_text(root, "cat-file", "-e", f"{resolved_ref}^{{tree}}")
        _git_text(root, "merge-base", "HEAD", resolved_ref)
        base_root = _extract_work_items_archive(root, resolved_ref)
        try:
            base_violations, _ = scan_tree(base_root)
        finally:
            import shutil
            shutil.rmtree(base_root, ignore_errors=True)
    except (OSError, UnicodeError, ValueError, RuntimeError, tarfile.TarError) as exc:
        print(f"ERROR: cannot verify diff base {base_ref!r}: {exc}", file=sys.stderr)
        return 2

    current_yaml = [v for v in current_violations if v.code == "SESSION_YAML_INVALID"]
    base_yaml = [v for v in base_violations if v.code == "SESSION_YAML_INVALID"]
    if base_yaml:
        print(f"BASE SESSION_YAML_INVALID: {len(base_yaml)} base-tree YAML error(s) treated as existing debt")
    introduced = _identities(current_violations) - _identities(base_violations)
    for v in sorted(current_violations, key=lambda item: (item.identity, item.detail)):
        if v.code == "SESSION_YAML_INVALID" or v.identity in introduced:
            print(f"NEW: {v.render()}")
    print(
        "SESSION IDENTITY DIFF: "
        f"violations={len(current_violations)} "
        f"base={len(base_violations)} "
        f"new={len(introduced) + len(current_yaml)}"
    )
    return 1 if current_yaml or introduced else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Check session identity using a shrink-only baseline."
    )
    parser.add_argument(
        "--baseline",
        type=Path,
        default=DEFAULT_BASELINE,
        help="baseline path relative to --root (default: %(default)s)",
    )
    parser.add_argument(
        "--write-baseline",
        action="store_true",
        help="shrink an existing baseline only; never create or expand it",
    )
    parser.add_argument(
        "--bootstrap-baseline",
        action="store_true",
        help="explicitly create the initial baseline from --base-ref",
    )
    parser.add_argument(
        "--base-ref",
        help="target-branch commit/ref required by --bootstrap-baseline",
    )
    parser.add_argument(
        "--diff-base",
        metavar="REF",
        help="fail only for findings introduced relative to this Git commit/ref",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=DEFAULT_ROOT,
        help="repository root (default: script-derived repository root)",
    )
    args = parser.parse_args(argv)

    if args.write_baseline and args.bootstrap_baseline:
        parser.error("--write-baseline and --bootstrap-baseline are mutually exclusive")
    if args.diff_base is not None and (args.write_baseline or args.bootstrap_baseline):
        parser.error("--diff-base is mutually exclusive with baseline mutation modes")
    if args.base_ref and not args.bootstrap_baseline:
        parser.error("--base-ref requires --bootstrap-baseline")

    root = args.root.resolve()
    baseline_path = (
        args.baseline
        if args.baseline.is_absolute()
        else root / args.baseline
    )

    if not root.is_dir():
        print(f"ERROR: repository root does not exist: {root}", file=sys.stderr)
        return 2

    try:
        violations, no_evidence_section = scan_tree(root)
    except Exception as exc:
        print(
            f"ERROR: unable to scan repository: {type(exc).__name__}: {exc}",
            file=sys.stderr,
        )
        return 2

    if args.diff_base is not None:
        return _diff_base_check(root, args.diff_base, violations)

    if args.bootstrap_baseline:
        return _bootstrap_baseline(
            root,
            baseline_path,
            args.base_ref,
            violations,
        )

    if args.write_baseline:
        return _write_baseline(baseline_path, violations)

    try:
        baseline = _parse_baseline(baseline_path)
    except FileNotFoundError:
        print(f"ERROR: baseline missing: {baseline_path}", file=sys.stderr)
        return 2
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"ERROR: invalid baseline: {exc}", file=sys.stderr)
        return 2

    return _print_check_result(violations, no_evidence_section, baseline)


if __name__ == "__main__":
    raise SystemExit(main())
